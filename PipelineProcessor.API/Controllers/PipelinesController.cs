using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using PipelineProcessor.Models;
using PipelineProcessor.Persistence;
using PipelineProcessor.Persistence.Entities;

namespace PipelineProcessor.Controllers;

// ============================================================================
// PipelinesController
// ----------------------------------------------------------------------------
// This controller owns the pipeline resource:
//
//   POST /pipelines          -> register a pipeline and its physical properties
//   GET  /pipelines/{id}     -> read one pipeline
//   PUT  /pipelines          -> placeholder for a future update endpoint
//
// The controller is deliberately thin: it validates the request, maps it to an
// entity, saves it, and returns HTTP responses. It does not contain engineering
// calculations; those belong in a separate pure calculator class later.
// ============================================================================

[ApiController]
[Route("pipelines")]
[Tags("Pipelines")]
public class PipelinesController : ControllerBase
{
    // The DbContext is injected by ASP.NET Core's dependency-injection
    // container. The controller never constructs a database connection itself.
    private readonly PipelineDbContext _pipelineDbContext;

    public PipelinesController(PipelineDbContext pipelineDbContext)
    {
        _pipelineDbContext = pipelineDbContext;
    }

    /// <summary>
    /// Registers a new pipeline: diameter, wall thickness, steel grade,
    /// strength, operating pressure and (optionally) its route on the map.
    /// </summary>
    [HttpPost]
    public async Task<IActionResult> CreatePipeline(
        CreatePipelineDto pipelineToCreate,
        CancellationToken cancellationToken)
    {
        // --------------------------------------------------------------------
        // Step 1: validate the incoming data.
        // --------------------------------------------------------------------
        // These guards prevent physically impossible or meaningless pipelines
        // from reaching the database. Invalid input is the client's fault, so
        // the response is 400 Bad Request.
        //
        // HINT: if more rules appear later (route shape, grade/SMYS agreement,
        // duplicate names, etc.), move this block into a separate validator
        // class, for example PipelineValidator or CreatePipelineValidator.
        // That class can return a list of error messages, leaving this action
        // responsible only for HTTP concerns. FluentValidation or data
        // annotations are alternative ways to do the same thing.
        if (string.IsNullOrWhiteSpace(pipelineToCreate.Name))
        {
            return BadRequest(new { error = "name is required." });
        }

        if (pipelineToCreate.OuterDiameterMm <= 0 || pipelineToCreate.WallThicknessMm <= 0)
        {
            return BadRequest(new { error = "outerDiameterMm and wallThicknessMm must be greater than zero." });
        }

        // A wall thicker than half the diameter is not a pipe; it is a solid
        // bar. This also catches the common mistake of swapping diameter and
        // wall thickness in the request.
        if (pipelineToCreate.WallThicknessMm >= pipelineToCreate.OuterDiameterMm / 2)
        {
            return BadRequest(new { error = "wallThicknessMm must be less than half the outer diameter." });
        }

        // SMYS is the steel strength and MAOP is the maximum allowed pressure.
        // Both are used by the later B31G calculation, so zero or negative
        // values would make the assessment meaningless.
        if (pipelineToCreate.SmysMpa <= 0 || pipelineToCreate.MaopMpa <= 0)
        {
            return BadRequest(new { error = "smysMpa and maopMpa must be greater than zero." });
        }

        // --------------------------------------------------------------------
        // Step 2: map the DTO to a database entity.
        // --------------------------------------------------------------------
        // The API accepts a DTO so that the wire format can differ from the
        // database shape. Text is trimmed to avoid storing accidental spaces.
        // CreatedAt is generated by the server, not trusted from the client.
        var newPipeline = new Pipeline
        {
            Name = pipelineToCreate.Name.Trim(),
            OuterDiameterMm = pipelineToCreate.OuterDiameterMm,
            WallThicknessMm = pipelineToCreate.WallThicknessMm,
            Grade = pipelineToCreate.Grade?.Trim() ?? string.Empty,
            SmysMpa = pipelineToCreate.SmysMpa,
            MaopMpa = pipelineToCreate.MaopMpa,
            RouteGeoJson = ReadRouteGeoJson(pipelineToCreate),
            CreatedAt = DateTime.UtcNow
        };

        // --------------------------------------------------------------------
        // Step 3: save the new pipeline.
        // --------------------------------------------------------------------
        // The id is generated in the entity's initializer (a GUID). SaveChanges
        // translates the Add into an INSERT and lets the database enforce its
        // constraints.
        _pipelineDbContext.Pipelines.Add(newPipeline);
        await _pipelineDbContext.SaveChangesAsync(cancellationToken);

        // --------------------------------------------------------------------
        // Step 4: return 201 Created.
        // --------------------------------------------------------------------
        // CreatedAtAction does two useful things:
        //   - sets the HTTP status to 201 Created
        //   - adds a Location header pointing at GetPipeline for this id
        // The body contains the newly created pipeline, including its id and
        // server-generated CreatedAt value.
        return CreatedAtAction(nameof(GetPipeline), new { pipelineId = newPipeline.Id }, newPipeline);
    }

    /// <summary>
    /// Placeholder for updating a pipeline. The route exists so the API shape
    /// is stable, but no update logic has been implemented yet.
    /// </summary>
    [HttpPut]
    public IActionResult UpdatePipeline(UpdatePipelineDto pipelineToUpdate)
    {
        // A real implementation would:
        //   1. find the pipeline by pipelineToUpdate.Id,
        //   2. return 404 if it does not exist,
        //   3. validate the new values (reuse the validator idea above),
        //   4. copy the allowed fields onto the tracked entity,
        //   5. save and return 204 No Content or the updated resource.
        return Ok();
    }

    /// <summary>
    /// Returns one pipeline by its id.
    /// </summary>
    [HttpGet("{pipelineId}")]
    public async Task<IActionResult> GetPipeline(
        string pipelineId,
        CancellationToken cancellationToken)
    {
        // AsNoTracking is enough for a read-only endpoint: EF Core does not
        // need to keep the entity in its change tracker. It is cheaper and
        // avoids accidentally modifying the row later in this request.
        var pipeline = await _pipelineDbContext.Pipelines
            .AsNoTracking()
            .FirstOrDefaultAsync(item => item.Id == pipelineId, cancellationToken);

        // The pipeline may not exist, or the id may be malformed. Either way a
        // 404 is the correct response: the resource is not available.
        if (pipeline is null)
        {
            return NotFound();
        }

        return Ok(pipeline);
    }

    /// <summary>
    /// Reads the route from whichever shape the client used:
    ///   - "routeGeoJson": a JSON string containing GeoJSON, or
    ///   - "route": a JSON object (as in tools/sample-data/pipeline.json).
    /// The database stores the result as a single string.
    /// </summary>
    private static string ReadRouteGeoJson(CreatePipelineDto pipeline)
    {
        // Preferred form: the client already serialized the GeoJSON.
        if (!string.IsNullOrWhiteSpace(pipeline.RouteGeoJson))
        {
            return pipeline.RouteGeoJson;
        }

        // If "route" is missing, null or undefined, there is no map geometry.
        // The database column is NOT NULL, so store an empty string instead of
        // null.
        if (pipeline.Route is not { ValueKind: not System.Text.Json.JsonValueKind.Null and not System.Text.Json.JsonValueKind.Undefined } route)
        {
            return string.Empty;
        }

        // A JSON string arrives as a string value; an object (the normal case)
        // is stored using its raw JSON text. Either way RouteGeoJson becomes a
        // valid string for the "longtext" column.
        return route.ValueKind == System.Text.Json.JsonValueKind.String
            ? route.GetString() ?? string.Empty
            : route.GetRawText();
    }
}
